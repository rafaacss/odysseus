  // Patterns for short dynamic strings JS builds with a number, e.g.
  // "3 Selected" or "120 lines" — exact-match DICT can't catch these.
  var REGEX_RULES = [
    [/^(\d+)\s+[Ss]elected$/, function (m) { return m[1] + " selecionado(s)"; }],
    [/^(\d+)\s+lines$/, function (m) { return m[1] + " linhas"; }],
    [/^(\d+)\s+sec$/, function (m) { return m[1] + " seg"; }],
    [/^(\d+)\s+uses?$/, function (m) { return m[1] + " uso(s)"; }]
  ];

  function translate(str) {
    var trimmed = str.trim();
    if (!trimmed) return null;
    if (Object.prototype.hasOwnProperty.call(DICT, trimmed)) {
      return str.replace(trimmed, DICT[trimmed]);
    }
    for (var i = 0; i < REGEX_RULES.length; i++) {
      var m = trimmed.match(REGEX_RULES[i][0]);
      if (m) return str.replace(trimmed, REGEX_RULES[i][1](m));
    }
    return null;
  }

  // Containers holding organic / dynamic content we must never touch:
  // chat transcript, document/notes editors, raw text inputs, code, scripts.
  var SKIP_SELECTOR = "#chat-history, [contenteditable], textarea, code, pre, script, style";

  function isInSkippedContainer(node) {
    var el = node.nodeType === 1 ? node : node.parentElement;
    while (el) {
      if (el.matches && el.matches(SKIP_SELECTOR)) return true;
      el = el.parentElement;
    }
    return false;
  }

  var ATTRS = ["placeholder", "title", "aria-label"];

  function translateElementAttrs(el) {
    if (!el.getAttribute) return;
    for (var i = 0; i < ATTRS.length; i++) {
      var a = ATTRS[i];
      var v = el.getAttribute(a);
      if (v) {
        var t = translate(v);
        if (t !== null) el.setAttribute(a, t);
      }
    }
  }

  function translateTextNode(node) {
    if (!node.nodeValue || !node.nodeValue.trim()) return;
    var t = translate(node.nodeValue);
    if (t !== null) node.nodeValue = t;
  }

  function walk(root) {
    if (root.nodeType === 1) {
      if (isInSkippedContainer(root)) return;
      translateElementAttrs(root);
    }
    var walker = document.createTreeWalker(
      root,
      NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT,
      null
    );
    var node;
    while ((node = walker.nextNode())) {
      if (node.nodeType === 1) {
        if (isInSkippedContainer(node)) continue;
        translateElementAttrs(node);
      } else if (node.nodeType === 3) {
        if (isInSkippedContainer(node)) continue;
        translateTextNode(node);
      }
    }
  }

  function run() {
    walk(document.body);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", run);
  } else {
    run();
  }

  // Odysseus is a dynamic SPA — most panels render after initial load.
  // Re-translate whenever new nodes show up.
  var observer = new MutationObserver(function (mutations) {
    for (var i = 0; i < mutations.length; i++) {
      var m = mutations[i];
      if (m.type === "childList") {
        for (var j = 0; j < m.addedNodes.length; j++) {
          var n = m.addedNodes[j];
          if (n.nodeType === 1 || n.nodeType === 3) walk(n);
        }
      } else if (m.type === "attributes" && ATTRS.indexOf(m.attributeName) !== -1) {
        if (m.target.nodeType === 1 && !isInSkippedContainer(m.target)) {
          translateElementAttrs(m.target);
        }
      } else if (m.type === "characterData") {
        if (!isInSkippedContainer(m.target)) translateTextNode(m.target);
      }
    }
  });
  observer.observe(document.body || document.documentElement, {
    childList: true,
    subtree: true,
    attributes: true,
    attributeFilter: ATTRS,
    characterData: true
  });
